package github

type Platform string
type Arch string

var (
	Windows Platform = "win"
	Linux   Platform = "linux"
	Darwin  Platform = "osx"

	Arm64   Arch = "arm64"
	Amd64   Arch = "x64"
	Arm     Arch = "arm"
	Ppc64le Arch = "ppc64le"
	S390x   Arch = "s390x"
)

type GithubRunnerArgs struct {
	Token          string
	RepoURL        string
	Org            string
	Name           string
	Platform       *Platform
	Arch           *Arch
	Labels         []string
	User           string
	AppID          string
	InstallationID string
	PrivateKeyPath string
	Ephemeral      bool
	// JITConfig is a just-in-time runner config generated by the caller. When set,
	// the runner starts from it instead of registering with Token.
	JITConfig string
}
